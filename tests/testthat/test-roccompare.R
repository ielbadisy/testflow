test_that("testroccompare matches pROC::roc.test(method = 'delong', paired = TRUE)", {
  skip_if_not_installed("pROC")
  set.seed(1)
  y <- rbinom(150, 1, 0.4)
  d <- data.frame(y = y, m1 = y + rnorm(150), m2 = round(0.6 * y + rnorm(150), 1))
  r <- testroccompare(d, m1, m2, y, plot = FALSE)
  r1 <- pROC::roc(d$y, d$m1, direction = "<", levels = c(0, 1), quiet = TRUE)
  r2 <- pROC::roc(d$y, d$m2, direction = "<", levels = c(0, 1), quiet = TRUE)
  ref <- pROC::roc.test(r1, r2, method = "delong", paired = TRUE)
  expect_equal(r$primary_test$statistic, unname(ref$statistic))
  expect_equal(r$primary_test$p.value, ref$p.value)
  expect_equal(c(r$primary_test$conf.low, r$primary_test$conf.high), as.numeric(ref$conf.int))
  expect_equal(r$alternative_tests$auc_table$auc, c(as.numeric(r1$auc), as.numeric(r2$auc)))
  ci1 <- pROC::ci.auc(r1, method = "delong")
  expect_equal(r$alternative_tests$auc_table$conf.low[1], ci1[1])
})

test_that("testroccompare prints and plots", {
  set.seed(2)
  y <- rbinom(80, 1, 0.5)
  d <- data.frame(y = factor(y, labels = c("no", "yes")), a = y + rnorm(80), b = rnorm(80))
  r <- testroccompare(d, a, b, y)
  expect_s3_class(r$plot, "ggplot")
  expect_output(print(r), "AUCs \\(DeLong\\)")
})
