test_that("testtwogroups method fixes the primary test", {
  set.seed(1)
  df <- data.frame(g = rep(c("a", "b"), each = 20))
  df$y <- c(stats::rnorm(20), stats::rnorm(20, 1, 3))
  w <- testtwogroups(y ~ g, df, method = "welch", plot = FALSE)
  s <- testtwogroups(y ~ g, df, method = "student", plot = FALSE)
  r <- testtwogroups(y ~ g, df, method = "wilcoxon", plot = FALSE)
  expect_equal(w$primary_test$p.value, stats::t.test(y ~ g, df)$p.value)
  expect_equal(s$primary_test$p.value, stats::t.test(y ~ g, df, var.equal = TRUE)$p.value)
  expect_equal(r$primary_test$p.value, stats::wilcox.test(y ~ g, df, exact = FALSE)$p.value)
  expect_match(w$recommended$rationale, "Pre-specified")
  a <- testtwogroups(y ~ g, df, plot = FALSE)
  expect_equal(a$recommended$test, testtwogroups(y ~ g, df, method = "auto", plot = FALSE)$recommended$test)
})
