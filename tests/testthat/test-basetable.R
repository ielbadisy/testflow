test_that("as.data.frame() gives a plain one-row data frame; as_tibble() a basetable", {
  dat <- make_cardio_data(80)
  x <- test_two_groups(dat, sbp_3m, sex)
  df <- as.data.frame(x)
  expect_identical(class(df), "data.frame")
  expect_equal(nrow(df), 1)
  bt <- as_tibble(x)
  expect_s3_class(bt, "basetable")
  expect_equal(names(df), names(bt))

  ss <- sample_size_continuous(delta = 5, sd = 10)
  expect_identical(class(as.data.frame(ss)), "data.frame")
  expect_s3_class(as_tibble(ss), "basetable")
})

test_that("column selection accepts names, strings, ranges, helpers and exclusions", {
  d <- data.frame(id = 1, t1 = 1, t2 = 2, t3 = 3, x = 0)
  sel <- function(v) tidyselect_names(d, {{ v }})
  expect_equal(sel(c(t1, t2, t3)), c("t1", "t2", "t3"))
  expect_equal(sel(t1:t3), c("t1", "t2", "t3"))
  expect_equal(sel(starts_with("t")), c("t1", "t2", "t3"))
  expect_equal(sel(-id), c("t1", "t2", "t3", "x"))
  expect_equal(sel(c("t1", "x")), c("t1", "x"))
  vv <- c("t2", "t3")
  expect_equal(sel(all_of(vv)), vv)
  expect_error(sel(c(t1, nope)))
  expect_error(sel(c("t1", "nope")), "not found")
})

test_that(".bt() follows tibble rules", {
  a <- .bt(x = 1:3, y = x * 2, z = "k", w = NULL)
  expect_s3_class(a, "basetable")
  expect_equal(names(a), c("x", "y", "z"))
  expect_equal(a$y, c(2, 4, 6))
  expect_equal(a$z, rep("k", 3))
  expect_equal(names(.bt(`p value` = 1)), "p value")
  expect_error(.bt(x = 1:3, y = 1:2), "compatible")
  expect_equal(nrow(.bt(a = character())), 0)
})
